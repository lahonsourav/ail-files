// Rasterized well above the largest badge size any layout actually uses
// (badges top out under 1"), so the glyph stays crisp — pptxgenjs scales
// the image down to whatever w/h the caller requests.
const ICON_PIXEL_SIZE = 128;

async function renderIconPng(icon: IllustrationIcon, hexColor: string): Promise<string> {
  // Dynamic import, not a static top-level one — Next.js's bundler treats
  // any file that statically imports react-dom/server as reachable from
  // React's server-component rendering path and refuses to compile it, even
  // though this module has nothing to do with rendering pages (it's a plain
  // Node-side SVG-to-PNG utility called from an API route). A dynamic
  // import sidesteps that static-reachability check.
  const { renderToStaticMarkup } = await import("react-dom/server");
  const svg = renderToStaticMarkup(
    React.createElement(ICON_COMPONENTS[icon], { color: `#${hexColor}`, size: ICON_PIXEL_SIZE })
  );
  const png = await sharp(Buffer.from(svg)).resize(ICON_PIXEL_SIZE, ICON_PIXEL_SIZE).png().toBuffer();
  return png.toString("base64");
}

// key: `${icon}:${hexColor}` -> base64 PNG (no "data:" prefix — addImage
// wants that added at the call site, same as any other pptxgenjs image use).
export type IconCache = Map<string, string>;

function cacheKey(icon: IllustrationIcon, hexColor: string): string {
  return `${icon}:${hexColor}`;
}

// Pre-renders every (icon, color) pair a single deck export actually needs,
// so the rest of buildPptx's per-slide loop — which calls pptxgenjs's
// synchronous addImage/addShape/addText API throughout — never has to await
// anything mid-render. A deck only ever draws icons in at most two colors
// (the theme's accent, and whichever color contrasts with it), so this is a
// handful of renders even for a deck that uses every icon in the set.
export async function buildIconCache(icons: Iterable<IllustrationIcon>, hexColors: Iterable<string>): Promise<IconCache> {
  const cache: IconCache = new Map();
  const iconList = Array.from(new Set(icons));
  const colorList = Array.from(new Set(hexColors));
  await Promise.all(
    iconList.flatMap((icon) =>
      colorList.map(async (hexColor) => {
        cache.set(cacheKey(icon, hexColor), await renderIconPng(icon, hexColor));
      })
    )
  );
  return cache;
}

export function getIconPng(cache: IconCache, icon: IllustrationIcon, hexColor: string): string | undefined {
  return cache.get(cacheKey(icon, hexColor));
}
